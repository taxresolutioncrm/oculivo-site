import fs from 'node:fs'
const read=(p)=>fs.readFileSync(new URL('../'+p,import.meta.url),'utf8')
const fail=(m)=>{console.error('FAIL:',m);process.exitCode=1}
const pass=(m)=>console.log('PASS:',m)
const check=(ok,m)=>ok?pass(m):fail(m)

const base=read('src/layouts/Base.astro')
const worker=read('src/worker.js')
const pricing=read('src/pages/pricing/index.astro')
const sitemap=read('src/pages/sitemap.xml.ts')
const resources=read('src/data/seoResources.ts')
const resourceIndex=read('src/pages/resources/index.astro')
const resourceTemplate=read('src/pages/resources/[slug].astro')
const optometry=read('src/pages/optometry-software/index.astro')
const ophthalmology=read('src/pages/ophthalmology-software/index.astro')
const optical=read('src/pages/optical-management/index.astro')
const pkg=JSON.parse(read('package.json'))

check(base.includes('href="/pricing/">Pricing</a>'),'Pricing is linked in repository navigation')
check(base.includes('href="/security/">Security</a>'),'Security is linked from the public site')
check(!base.includes('\\n'),'Base metadata has no literal newline escapes')
check(base.includes('schema')&&base.includes('JSON.stringify(schema)'),'Page-specific structured data can be rendered alongside site schema')
const mainLinks=(base.match(/<div class="main-links">([\s\S]*?)<\/div>/)||[])[1]||''
const mobileLinks=(base.match(/<div class="mobile-nav-panel">([\s\S]*?)<\/div>/)||[])[1]||''
check(!mainLinks.includes('/website-seo')&&!mobileLinks.includes('/website-seo'),'Website + SEO is removed from primary desktop/mobile navigation')
check(base.includes('href="/resources/">Practice resources</a>'),'SEO resource library remains internally linked from the footer')
check(worker.includes("'/pricing'")&&worker.includes("'/pricing/'"),'Worker serves pricing from repository assets')
check(worker.includes("'/security'")&&worker.includes("'/security/'"),'Worker serves security from repository assets')
check(worker.includes("incoming.pathname === '/resources'")&&worker.includes("incoming.pathname.startsWith('/resources/')"),'Worker serves the SEO resource library from repository assets')
check(worker.includes('Website\\s*\\+\\s*SEO')&&worker.includes("'/website-seo"),'Proxied legacy navigation strips the Website + SEO tab')
check(worker.includes("'/favicon.svg'")&&worker.includes("'/site.webmanifest'"),'Worker serves current brand assets')
check(worker.includes('G-WR6GGVYLXX')&&worker.includes('yguz2tkhnt'),'GA4 and Clarity injection guards are present')
check(worker.includes('BC8190C5D48F98C3E4C4A6EC29AA5CB3'),'Bing verification is preserved')
check(['$399/mo','$599/mo','$799/mo'].every(x=>pricing.includes(x)),'All three approved pricing tiers are present')
check(pricing.includes('AggregateOffer'),'Pricing structured data is present')
check(sitemap.includes("'pricing/'")&&sitemap.includes("'security/'"),'Pricing and security are in the sitemap')
check(!sitemap.includes("'demo/'"),'Redirect-only demo route is excluded from sitemap')
check(sitemap.includes("'resources/'")&&sitemap.includes('seoResources.map'),'SEO resource library and generated guides are in the sitemap')
check((resources.match(/slug:/g)||[]).length>=10,'At least ten query-focused SEO resource guides are defined')
check(resourceIndex.includes('seoResources.map'),'Resource hub links all generated SEO guides')
check(resourceTemplate.includes("'@type':'Article'")&&resourceTemplate.includes("'@type':'FAQPage'"),'Generated resource pages include Article and FAQ structured data')
check(optometry.includes('Cloud-Based Optometry Practice Management Software')&&optometry.includes("'@type':'FAQPage'")&&optometry.includes('/resources/optometry-software-buyers-guide/'),'Optometry pillar targets commercial cloud/practice-management intent with FAQ and internal links')
check(ophthalmology.includes('Cloud-Based Ophthalmology Practice Management Software')&&ophthalmology.includes("'@type':'FAQPage'")&&ophthalmology.includes('/resources/ophthalmology-referral-workflow/'),'Ophthalmology pillar targets commercial cloud/practice-management intent with FAQ and internal links')
check(optical.includes('Optical Inventory & Order Management Software')&&optical.includes("'@type':'FAQPage'")&&optical.includes('/resources/optical-inventory-management-guide/'),'Optical pillar targets inventory/order intent with FAQ and internal links')
const seo=read('src/pages/website-seo/index.astro')
check(!/reputation management|call tracking|appointment attribution|portal messages|portal conversations|automation/i.test(pricing+'\n'+seo),'Pricing and SEO pages contain no unsupported marketing claims')
check(pkg.devDependencies?.astro==='4.16.18'&&pkg.devDependencies?.typescript==='5.6.3'&&pkg.devDependencies?.wrangler==='4.20.0','Website toolchain versions are pinned')
if(process.exitCode)process.exit(process.exitCode)
